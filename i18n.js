let LANG = (() => {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if(saved === 'en' || saved === 'tr') return saved;
  } catch {}
  return (navigator.language || '').toLowerCase().startsWith('tr') ? 'tr' : 'en';
})();
const LOCALE = () => LANG === 'tr' ? 'tr-TR' : 'en-GB';

function t(key, vars = {}){
  const s = STRINGS[LANG][key] ?? STRINGS.en[key] ?? key;
  if(typeof s === 'function') return s(vars);
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}
const fmtNum = (n, opts) => Number(n).toLocaleString(LOCALE(), opts);
const catName = c => t('cat.' + c);
// Dispute reasons are stored as keys; older saved requests may hold the English text itself
const reasonText = r => STRINGS.en['reason.' + r] ? t('reason.' + r) : String(r ?? '');

function applyStatic(){
  document.documentElement.lang = LANG;
  document.title = t('meta.title');
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  document.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
  document.querySelectorAll('[data-i18n-alt]').forEach(el => { el.alt = t(el.dataset.i18nAlt); });
  document.querySelectorAll('[data-star]').forEach(el => el.setAttribute('aria-label', t('rate.star', {n:Number(el.dataset.star)})));
  document.querySelectorAll('[data-lang]').forEach(b => {
    b.classList.toggle('on', b.dataset.lang === LANG);
    b.setAttribute('aria-pressed', String(b.dataset.lang === LANG));
  });
}

function setLang(lang){
  if(lang !== 'en' && lang !== 'tr') return;
  LANG = lang;
  try { localStorage.setItem(LANG_KEY, lang); } catch {}
  applyStatic();
  if(typeof onLangChange === 'function') onLangChange();
}
